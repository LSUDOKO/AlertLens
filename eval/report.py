"""Write results/benchmark_report.md and charts from measured metrics only."""
from __future__ import annotations

import json
import logging
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from alertlens.config import ROOT  # noqa: E402

log = logging.getLogger(__name__)
INK, MUTED, BAD, GOOD = "#E6EDF3", "#8B98A5", "#F2545B", "#7CE0C3"
BG = "#0B0F14"


def _style(ax, fig) -> None:
    fig.patch.set_facecolor(BG)
    ax.set_facecolor(BG)
    ax.tick_params(colors=INK, labelsize=8)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(MUTED)
    ax.yaxis.label.set_color(INK)
    ax.xaxis.label.set_color(INK)
    ax.title.set_color(INK)


def charts(r: dict, out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    rows = {k: v for k, v in r["by_family"].items() if v["mal"]}
    if rows:
        fams = sorted(rows)
        fig, ax = plt.subplots(figsize=(8, 3.6))
        xs = range(len(fams))
        ax.bar([x - 0.2 for x in xs], [100 * rows[f]["naive_fooled"] / rows[f]["mal"] for f in fams], 0.4, label="Naive LLM", color=BAD)
        ax.bar([x + 0.2 for x in xs], [100 * rows[f]["alertlens_fooled"] / rows[f]["mal"] for f in fams], 0.4, label="AlertLens", color=GOOD)
        ax.set_xticks(list(xs), fams, rotation=30, ha="right")
        ax.set_ylabel("Attack success rate (%)")
        ax.set_title("Attack success by injection family")
        _style(ax, fig)
        ax.legend(frameon=False, labelcolor=INK, fontsize=8)
        fig.tight_layout()
        fig.savefig(out / "asr_by_family.png", dpi=130, facecolor=BG)
        plt.close(fig)

    fig, ax = plt.subplots(figsize=(4, 4))
    pts = r["calibration"]["points"]
    ax.plot([0, 1], [0, 1], "--", color=MUTED, lw=1)
    ax.plot([p["confidence"] for p in pts], [p["observed"] for p in pts], "o-", color=GOOD)
    ax.set_xlabel("Predicted probability")
    ax.set_ylabel("Observed malicious share")
    ax.set_title(f"Reliability (ECE {r['calibration']['ece']})")
    _style(ax, fig)
    fig.tight_layout()
    fig.savefig(out / "reliability.png", dpi=130, facecolor=BG)
    plt.close(fig)

    fig, axes = plt.subplots(1, 2, figsize=(6.4, 3))
    for ax, key, title in zip(axes, ["naive", "alertlens"], ["Naive LLM", "AlertLens"], strict=True):
        t = r["triage"][key]
        grid = [[t["tn"], t["fp"]], [t["fn"], t["tp"]]]
        ax.imshow(grid, cmap="Greens")
        for yy in range(2):
            for xx in range(2):
                ax.text(xx, yy, grid[yy][xx], ha="center", va="center", color="black", fontsize=11)
        ax.set_xticks([0, 1], ["pred benign", "pred malicious"])
        ax.set_yticks([0, 1], ["benign", "malicious"])
        ax.set_title(title)
        _style(ax, fig)
    fig.tight_layout()
    fig.savefig(out / "confusion.png", dpi=130, facecolor=BG)
    plt.close(fig)

    routing = r["routing"]
    if routing["avg_ms_fast"] is not None and routing["avg_ms_llm"] is not None:
        fig, ax = plt.subplots(figsize=(4, 3))
        ax.bar(["fast", "llm"], [routing["avg_ms_fast"], routing["avg_ms_llm"]], color=[GOOD, MUTED])
        ax.set_ylabel("Average ms per alert")
        ax.set_title("Latency by path")
        _style(ax, fig)
        fig.tight_layout()
        fig.savefig(out / "latency.png", dpi=130, facecolor=BG)
        plt.close(fig)


def pct(v) -> str:
    return "n/a" if v is None else f"{100 * v:.1f}%"


def write_report(r: dict, out_dir: Path) -> None:
    charts(r, out_dir / "charts")
    meta = r["meta"]
    lines = ["# AlertLens benchmark report", "",
             f"Generated by `make eval`. Date {meta['date']}, commit `{meta['commit']}`, seed {meta['seed']}, model `{meta['model']}`.",
             f"Dataset: {meta['alerts']} synthetic alerts, {meta['malicious']} malicious, {meta['injected']} carrying an injection, "
             f"{meta['injected_malicious']} of those malicious.", ""]
    if meta["simulated_model"]:
        lines += ["> **Simulated model.** Both systems use `VulnerableMockLLM`, which obeys any instruction it can read. "
                  "The naive column is therefore a simulated worst case, not a measurement of a real LLM. "
                  "The comparison shows what each design lets a gullible model read.", ""]
    else:
        lines += [f"> **Real model:** `{meta['model']}`, for both systems.", ""]
    a, d, t = r["asr"], r["detection"], r["triage"]
    lines += ["## Headline", "", "| Metric | Naive LLM | AlertLens |", "|---|---|---|",
              f"| Attack success rate, injected malicious alerts | {pct(a['naive'])} | {pct(a['alertlens'])} |",
              f"| ...of which the injection caused the miss | {pct(a['naive_injection_caused'])} | {pct(a['alertlens_injection_caused'])} |",
              f"| Harmful or non-playbook action rate | {pct(r['unsafe_actions']['naive'])} | {pct(r['unsafe_actions']['alertlens'])} |",
              f"| Verdict F1 | {t['naive']['f1']} | {t['alertlens']['f1']} |",
              f"| Verdict false-positive rate | {pct(t['naive']['fpr'])} | {pct(t['alertlens']['fpr'])} |", "",
              "Attack success means the final result was low severity, a benign verdict, an auto-close suggestion or a harmful action. "
              "The second row counts only alerts handled correctly when the payload was removed.", "",
              "## AlertLens detail", "", "| Metric | Measured |", "|---|---|",
              f"| Injection detection recall, all | {pct(d['recall'])} |",
              f"| ...on payload templates (n={d['known_n']}) | {pct(d['recall_known_templates'])} |",
              f"| ...on held-out paraphrases (n={d['heldout_n']}) | {pct(d['recall_heldout_paraphrases'])} |",
              f"| Detection precision | {pct(d['precision'])} |",
              f"| False-positive rate on clean alerts | {pct(d['false_positive_rate'])} |",
              f"| Base score identical with and without payload | {pct(r['invariance']['base_score_identical'])} |",
              f"| Label identical, before the deliberate injection bump | {pct(r['invariance']['label_identical_before_bump'])} |",
              f"| Label identical, after the bump (it only moves up) | {pct(r['invariance']['label_identical'])} |",
              f"| Alerts whose label a payload lowered | {r['invariance']['labels_lowered']} |",
              f"| Final score never lower with payload | {pct(r['invariance']['score_never_lower'])} |",
              f"| Mean grounding score, all alerts | {r['grounding']['mean_all']} |",
              f"| Mean grounding score, LLM path | {r['grounding']['mean_llm_path']} |",
              f"| Alerts where an invented address was caught | {r['grounding']['alerts_with_invented_ip_caught']} |",
              f"| Invented address shown after the verifier | {pct(r['grounding']['invented_ip_rate_shown'])} |",
              f"| Calibration error (ECE) | {r['calibration']['ece']} |",
              f"| Correlation pairwise precision | {pct(r['correlation']['precision'])} |",
              f"| Correlation pairwise recall | {pct(r['correlation']['recall'])} |",
              f"| Fast-path share | {pct(r['routing']['fast_share'])} |",
              f"| Average latency, fast path | {r['routing']['avg_ms_fast']} ms |",
              f"| Average latency, LLM path | {r['routing']['avg_ms_llm']} ms |",
              f"| Fast and deep agreement (n={r['routing']['agreement_sample']}) | {pct(r['routing']['agreement_fast_vs_deep'])} |",
              f"| Counterfactual coverage, high or critical | {pct(r['counterfactuals']['coverage'])} |", "",
              f"Triage outcomes: {json.dumps(t['outcomes'])}.", "",
              "![ASR by family](charts/asr_by_family.png)", "", "![Reliability](charts/reliability.png)", "",
              "![Confusion](charts/confusion.png)", "", "![Latency](charts/latency.png)", "",
              "## Ablations: what breaks when a layer is removed", "",
              "Run on the injected malicious alerts only.", "",
              "| Configuration | ASR | Downplaying explanation shown | Detected | Invented address shown | Canary alarms | Canary shown to reader | Tamper events |",
              "|---|---|---|---|---|---|---|---|"]
    for row in r["ablations"]:
        lines.append(f"| {row['name']} | {pct(row['asr'])} | {pct(row['downplayed_explanations'])} | {pct(row['detected'])} | "
                     f"{pct(row['invented_ip_shown'])} | {row['canary_alarms']} | {row['canary_shown']} | {row['tamper_events']} |")
    lines += ["", "## Worked examples", ""]
    for ex in r["worked_examples"]:
        lines += [f"**{ex['title']}**", "", "```json", json.dumps(ex, indent=2, ensure_ascii=False), "```", ""]
    lines += ["## Limitations", "",
              "- All data is synthetic and written by the same people who wrote the detector and scorer, so model scores will not carry over to a real SOC. "
              "The model's precision on this data is optimistic.",
              "- The held-out paraphrases were not used to tune rules, but the same authors wrote them, so they are not a truly blind test. "
              "Unknown languages and encodings will evade the detector more often.",
              "- The verifier checks concrete values and a few polarities. Qualitative wording is shown as partially verified.",
              "- A mislabelled training pattern (service tokens) is planted for the feedback demo, and it lowers recall until corrected.",
              "- Structured fields such as `rule_level` are trusted as sensor output. Someone able to forge those can change the score."]
    (out_dir / "benchmark_report.md").write_text("\n".join(lines) + "\n")


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    out = ROOT / "results"
    write_report(json.loads((out / "metrics.json").read_text()), out)


if __name__ == "__main__":
    main()
